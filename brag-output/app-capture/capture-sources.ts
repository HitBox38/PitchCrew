import { chromium } from '../../packages/ui/node_modules/playwright/index.mjs';
import { resolve } from 'node:path';
import { writeFile } from 'node:fs/promises';
const output=resolve('brag-output/composition/assets/app');
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:2,reducedMotion:'reduce',colorScheme:'light'});
await page.goto('http://127.0.0.1:14417/');
await page.getByRole('button',{name:'Open Senior UI Engineer at Waypoint',exact:true}).click();
await page.getByRole('tab',{name:'Application',exact:true}).click();
await page.getByRole('button',{name:/^Documents/}).click();
await page.locator('.evidence').first().waitFor();
await page.locator('.evidence').nth(1).scrollIntoViewIfNeeded();
await page.getByRole('dialog').screenshot({path:`${output}/sources-panel.png`});
const heading=page.getByRole('heading',{name:'Sources',exact:true});
const hb=(await heading.boundingBox())!;
const end=(await page.locator('.evidence').nth(1).boundingBox())!;
const clip={x:hb.x-12,y:hb.y-12,width:568,height:end.y+end.height-hb.y+24};
if(clip.y>=0&&clip.y+clip.height<=1000)await page.screenshot({path:`${output}/sources-closeup.png`,clip});
console.log({heading:hb,claim:end,clip});
await writeFile(`${output}/source-state.json`,JSON.stringify({heading:hb,secondClaim:end,clip,component:'packages/ui/src/components/CardDetails/components/JobPacket.tsx'},null,2));
await browser.close();
