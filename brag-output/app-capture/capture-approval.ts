import { chromium } from '../../packages/ui/node_modules/playwright/index.mjs';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const output=resolve('brag-output/composition/assets/app');
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:2,reducedMotion:'reduce',colorScheme:'light'});
await page.goto('http://127.0.0.1:14417/inbox');
await page.getByRole('button',{name:/Pitchcrew Your application packet/}).click();
await page.getByRole('button',{name:'Approve packet',exact:true}).waitFor();
await page.evaluate(async()=>{await document.fonts.ready;});
console.log('READING',await page.locator('.mail-reading').innerText());
const reading=await page.locator('.mail-reading').boundingBox();
const button=await page.getByRole('button',{name:'Approve packet',exact:true}).boundingBox();
await page.screenshot({path:`${output}/approval-pending.png`});
await page.locator('.mail-reading').screenshot({path:`${output}/approval-panel.png`});
await page.getByRole('button',{name:'Approve packet',exact:true}).click();
await page.getByRole('button',{name:'Submit myself',exact:true}).waitFor();
await page.screenshot({path:`${output}/approval-approved.png`});
console.log('APPROVED',await page.locator('.mail-reading').innerText());
await writeFile(`${output}/approval-state.json`,JSON.stringify({viewport:{width:1600,height:1000},deviceScaleFactor:2,reading,approveButton:button,screens:['approval-pending.png','approval-approved.png'],fictional:true},null,2));
await browser.close();
